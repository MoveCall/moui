void moui_draw_icon(moui_draw_ctx_t *ctx, int x, int y, moui_icon_id_t id, moui_color_t color)
{
    if (id >= MOUI_ICON_COUNT || !s_icon_table[id]) return;
    moui_draw_bitmap(ctx, x, y, MOUI_ICON_W, MOUI_ICON_H, s_icon_table[id], color);
}

void moui_draw_icon_scaled(moui_draw_ctx_t *ctx, int x, int y, moui_icon_id_t id, uint8_t scale, moui_color_t color)
{
    if (id >= MOUI_ICON_COUNT || !s_icon_table[id]) return;
    if (scale <= 1) {
        moui_draw_bitmap(ctx, x, y, MOUI_ICON_W, MOUI_ICON_H, s_icon_table[id], color);
        return;
    }
    const uint8_t *bmp = s_icon_table[id];
    for (int ry = 0; ry < MOUI_ICON_H; ry++) {
        for (int rx = 0; rx < MOUI_ICON_W; rx++) {
            int byte_idx = ry * 2 + (rx >> 3);
            int bit_idx = 7 - (rx & 7);
            if (bmp[byte_idx] & (1 << bit_idx)) {
                moui_rect_t pixel_box = {
                    (int16_t)(x + rx * scale),
                    (int16_t)(y + ry * scale),
                    (uint16_t)scale,
                    (uint16_t)scale
                };
                moui_draw_fill_rect(ctx, &pixel_box, color);
            }
        }
    }
}

void moui_draw_icon_in_rect(moui_draw_ctx_t *ctx, const moui_rect_t *rect, moui_icon_id_t id, moui_color_t color)
{
    if (!rect) return;
    int ix = rect->x + (rect->w - MOUI_ICON_W) / 2;
    int iy = rect->y + (rect->h - MOUI_ICON_H) / 2;
    moui_draw_icon(ctx, ix, iy, id, color);
}

const char *moui_icon_get_name(moui_icon_id_t id)
{
    if (id >= MOUI_ICON_COUNT || !s_icon_names[id]) return "UNKNOWN";
    return s_icon_names[id];
}
